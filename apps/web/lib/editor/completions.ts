const commandOptions: Completion[] = COMMANDS.map(([name, args, detail]) =>
  args
    ? snippetCompletion(`\\${name}${args}`, {
        label: `\\${name}`,
        type: 'function',
        detail: detail ?? args.replace(/\$\{([^}]*)\}/g, '$1'),
      })
    : { label: `\\${name}`, type: 'constant' },
);

const beginOptions: Completion[] = ENVIRONMENTS.map((env) =>
  snippetCompletion(`\\begin{${env}}\n\t\${}\n\\end{${env}}`, {
    label: `\\begin{${env}}`,
    type: 'keyword',
    detail: 'environment',
    boost: 1,
  }),
);

const envNameOptions: Completion[] = ENVIRONMENTS.map((env) => ({ label: env, type: 'type' }));

/** Completes `\command`s, `\begin{…}` blocks and environment names. */
export function latexCompletions(context: CompletionContext): CompletionResult | null {
  const env = context.matchBefore(/\\(?:begin|end)\{[\w*]*/);
  if (env) {
    return {
      from: env.from + env.text.indexOf('{') + 1,
      options: envNameOptions,
      validFor: /^[\w*]*$/,
    };
  }
  const cmd = context.matchBefore(/\\[A-Za-z]*/);
  if (!cmd || (cmd.from === cmd.to && !context.explicit)) return null;
  return {
    from: cmd.from,
    options: [...beginOptions, ...commandOptions],
    validFor: /^\\[A-Za-z]*$/,
  };
}
